/**
 * The tracker contract, implemented in TypeScript for the host that cannot
 * run tk (SPEC §3.1, line 191; `contracts/tk-json-manifest.json` `hosts`).
 *
 * A Cloudflare Workflow or isolate cannot execute a Go binary, so on this
 * host the reconciler cannot shell out to tk. `tk --json` defines the tracker
 * contract; this module is its consumer implementation on that host: the
 * reads and controlled writes the manifest publishes, performed against
 * `.tick/` records through the contents API — and NOTHING ELSE. It is a
 * consumer of the contract, not a second tracker: every host that can run tk
 * runs tk, and this module exists only because its host cannot.
 *
 * Two things keep this implementation honest rather than merely present:
 *
 * 1. **The pinned fixtures certify it, not inspection.** `tracker-client.test.ts`
 *    validates every read's output against the manifest's own schemas, pins
 *    the behavioural rules the manifest's command descriptions state (null
 *    versus [], the ready ordering, the claim's idempotence, the note's
 *    provenance boundary, the close's refusals), and drives the encoder
 *    through `contracts/tracker-layout.json`. A fixture break fails this
 *    build. The module was written from the manifest and the behaviours the
 *    fixtures describe, not by eyeballing tk's output.
 *
 * 2. **The writes are tk's writes.** Each controlled write commits exactly
 *    the record `tk update`/`tk note`/`tk close`/`tk reopen` would commit —
 *    same field order (Go's `tick.Tick` struct), same `omitempty` rules, same
 *    string escaping (Go's encoding/json escapes `<`, `>`, `&` and the line
 *    separators; JSON.stringify does not), same idempotence (a re-claim
 *    keeps its `started_at`), same refusals (a tick with an unmet `--requires`
 *    gate is routed to `awaiting`, never closed) — because the two writers
 *    write the same files in the same repository, and a divergence is a
 *    record the other writer refuses. The proof is not this paragraph: the
 *    pinned tk corpus (cloudflare/test/fixtures/tk-write-corpus.json,
 *    generated by internal/tkcorpus from a real tk binary) byte-compares the
 *    client's committed records against tk's own for a generated corpus of
 *    writes, so neither side can drift quietly.
 *
 * What this module deliberately does NOT implement, and why:
 *
 *  - `tk version`: a property of a binary, and there is no binary here. The
 *    manifest's `version` entry is how a consumer checks the binary it is
 *    about to call; a host that does not call the binary has nothing to
 *    report. `manifestContract` below is the answer this host CAN give: which
 *    contract version its implementation targets.
 *  - `tk status` as a working-tree answer: this host reads `.tick/` at a
 *    commit, and a commit is always clean. `status()` reports that honestly
 *    (`changes: null`) rather than pretending to a porcelain it has no tree
 *    for. No caller of this client has a working tree to compare against.
 *  - `merge-file` / `merge-activity`: git custom merge DRIVERS, invoked by
 *    git with worktree paths. A Workflow has no worktree; the run branch is
 *    published, not merged locally.
 */

