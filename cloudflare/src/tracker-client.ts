/** The fields Go's struct never omits, whatever their value. */
const ALWAYS_PRESENT = new Set(["created_by", "created_at", "updated_at"]);

function isEmpty(value: unknown): boolean {
  if (value === undefined || value === null) return true;
  if (typeof value === "string") return value === "";
  if (Array.isArray(value)) return value.length === 0;
  if (typeof value === "boolean") return value === false;
  return false;
}

/**
 * Go's string escaping, applied to what JSON.stringify produced.
 *
 * Go's encoding/json — which is what tk writes records with — escapes more
 * than JSON.stringify does, even inside strings: `<`, `>`, `&` (its default
 * HTML escaping) and the two line separators U+2028/U+2029. Those are byte
 * differences between two writers of the same file (tick v3q): a record
 * this client writes must be the record tk would write, because the two
 * write the same files in the same repository and a divergence is a diff
 * nobody can review.
 *
 * Everything JSON.stringify emits for a string already matches current Go:
 * `\"`, `\\`, the `\n \r \t \b \f` short escapes, lowercase `\u00xx` for
 * the other control bytes, and raw UTF-8 for everything else. This pass
 * walks the serialized text and rewrites only inside string tokens, so
 * structural JSON (field names, braces, the numbers) is untouched.
 */
function goEscape(text: string): string {
  let out = "";
  let inString = false;
  for (let i = 0; i < text.length; i += 1) {
    const c = text.charAt(i);
    if (!inString) {
      if (c === '"') inString = true;
      out += c;
      continue;
    }
    if (c === '"') {
      inString = false;
      out += c;
      continue;
    }
    // Keep JSON.stringify's own escapes — they are Go's own for every byte
    // either of them escapes short (`\n`, `\t`, `\b`, `\f`, `\"`, `\\`,
    // `\u00xx`).
    if (c === "\\") {
      out += c;
      out += text.charAt(i + 1);
      i += 1;
      continue;
    }
    if (c === "<") {
      out += "\\u003c";
    } else if (c === ">") {
      out += "\\u003e";
    } else if (c === "&") {
      out += "\\u0026";
    } else if (c === "\u2028") {
      out += "\\u2028";
    } else if (c === "\u2029") {
      out += "\\u2029";
    } else {
      out += c;
    }
  }
  return out;
}

/**
 * Encodes one tick record the way Go's `Store.Write` does: `tick.Tick`'s
 * field order, `omitempty` on exactly the fields that carry it, two-space
 * indent, no trailing newline — and Go's own string escaping (see
 * `goEscape`), byte for byte what `json.MarshalIndent` writes.
 *
 * Field ORDER is part of the contract: this module and `tk` write the same
 * file in the same repository, and a diff that is real content one way and
 * field reordering the other is a diff nobody can review.
 * `tracker-layout.json`'s `written_by_the_control_plane` pins the indent and
 * the required-field set this encoder must not drift from; the pinned tk
 * corpus (cloudflare/test/fixtures/tk-write-corpus.json) byte-compares this
 * encoder's output against a real tk's.
 */
export function encodeTick(tick: Tick): string {
  const record: Record<string, unknown> = {};
  for (const field of TICK_FIELD_ORDER) {
    const value = (tick as Record<string, unknown>)[field];
    if (!ALWAYS_PRESENT.has(field) && isEmpty(value)) continue;
    record[field] = value;
  }
  return goEscape(JSON.stringify(record, null, 2));
}

/** The fields a record must carry for this client to read it (`#/$defs/tick`). */
export const TICK_REQUIRED_FIELDS = [
  "id",
  "title",
  "status",
  "priority",
  "type",
  "owner",
  "created_by",
  "created_at",
  "updated_at",
] as const;

/**
 * Parses one tick record. null (not a throw) when the text is not a record
 * `tk` would read: a file this host cannot parse is an answer — unreadable —
 * the same way `tick-membership.ts` treats it, never a crash.
 */
export function parseTick(text: string): Tick | null {
  let parsed: unknown;
  try {
    parsed = JSON.parse(text);
  } catch {
    return null;
  }
  if (typeof parsed !== "object" || parsed === null || Array.isArray(parsed)) return null;
  const record = parsed as Record<string, unknown>;
  for (const field of TICK_REQUIRED_FIELDS) {
    if (record[field] === undefined) return null;
  }
  if (typeof record.id !== "string" || typeof record.status !== "string") return null;
  if (typeof record.priority !== "number" || !Number.isSafeInteger(record.priority)) return null;
  return parsed as Tick;
}

